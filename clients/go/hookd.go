// Package hookd provides a Go client for the Hookd interaction logging server.
package hookd

import (
	"net/http"
	"sync"
	"time"
)

const Version = "1.4.0"

// DefaultMaxResponseBytes caps the buffered response body. It is generous
// because a poll can legitimately return many interactions with full bodies.
const DefaultMaxResponseBytes int64 = 64 << 20 // 64 MiB

// Client communicates with a Hookd server.
type Client struct {
	server           string
	token            string
	httpClient       *http.Client
	maxResponseBytes int64

	mu sync.Mutex
	// secret is the owner secret sent as X-Hookd-Secret. settled means it is
	// known, or the server proved it issues none, so registrations need not
	// be serialized to adopt one.
	secret   string
	settled  bool
	register sync.Mutex
}

// NewClient creates a new Hookd client.
func NewClient(server, token string) *Client {
	return &Client{
		server: server,
		token:  token,
		httpClient: &http.Client{
			Timeout: 30 * time.Second,
			Transport: &http.Transport{
				ResponseHeaderTimeout: 10 * time.Second,
			},
		},
		maxResponseBytes: DefaultMaxResponseBytes,
	}
}

// SetMaxResponseBytes overrides the response cap. Zero or less disables it.
func (c *Client) SetMaxResponseBytes(n int64) {
	c.maxResponseBytes = n
}

// SetSecret sets the owner secret sent with every request, for servers with
// owner secrets enabled: hooks registered with it are readable only with it.
// An empty secret lets the next registration adopt one the server generates.
func (c *Client) SetSecret(secret string) {
	c.mu.Lock()
	defer c.mu.Unlock()
	c.secret, c.settled = secret, secret != ""
}

// Secret returns the owner secret in use, which may have been generated by the
// server on the first registration. Store it to read the hooks later.
func (c *Client) Secret() string {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.secret
}
